// Hàm helper để lấy danh sách tỉnh/thành phố
export const getProvinces = () => {
  return Object.keys(vietnamAddresses);
};

// Hàm helper để lấy danh sách quận/huyện theo tỉnh
export const getDistricts = (province) => {
  if (!province || !vietnamAddresses[province]) return [];
  return Object.keys(vietnamAddresses[province]);
};

// Hàm helper để lấy danh sách phường/xã theo tỉnh và quận
export const getWards = (province, district) => {
  if (!province || !district || !vietnamAddresses[province] || !vietnamAddresses[province][district]) return [];
  return vietnamAddresses[province][district];
};

